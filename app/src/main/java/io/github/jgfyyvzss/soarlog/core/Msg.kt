package io.github.jgfyyvzss.soarlog.core

/**
 * User-visible text from code that cannot read Android string resources: a key and its arguments. The UI turns it
 * into text in the pilot's language, from `strings.xml`. Arguments may themselves be messages, dates, roles,
 * numbers or plain text.
 */
data class Msg(val key: MsgKey, val args: List<Any?> = emptyList())

fun msg(key: MsgKey, vararg args: Any?) = Msg(key, args.toList())

/** Every message key. Each has a `msg_<key>` string in `strings.xml`; the UI's lookup is exhaustive, so a missing one fails to compile. */
enum class MsgKey {
    // Flight form
    LOG_NO_POSITIVE, LOG_NO_USED, FLIGHT_ON, DATE_REQUIRED, DURATION_FORMAT, DURATION_RANGE, GLIDER_REQUIRED,
    AIRFIELD_REQUIRED, CLUB_REQUIRED, LAUNCH_TYPE_REQUIRED, PIC_REQUIRED, PIC_OTHER_REQUIRED, TIME_FORMAT,
    LANDING_AFTER_LAUNCH, LANDING_AIRFIELD_REQUIRED, LANDING_PLACE_REQUIRED, TIMES_DISAGREE,

    // Records
    REGISTRATION_REQUIRED, GLIDER_EXISTS, GLIDER_GONE, LOGBOOK_HOURS_AND_DATE, FLIGHTS_NEGATIVE, AIRFIELD_NAME_REQUIRED,
    COORDINATES_BOTH, LATITUDE_RANGE, LONGITUDE_RANGE, RADIUS_POSITIVE, AIRFIELD_EXISTS, CLUB_NAME_REQUIRED, CLUB_EXISTS,
    LAUNCH_TYPE_NAME_REQUIRED, LAUNCH_TYPE_EXISTS, BALANCES_NEGATIVE,

    // CSV import
    CSV_ERROR_FOUND, CSV_ERROR_COLUMN, CSV_ERROR_ROW, CSV_BLANK, CSV_EXPECT_HEADER, CSV_EXPECT_COLUMN, CSV_EXPECT_POSITIVE,
    CSV_EXPECT_WHOLE, CSV_EXPECT_LOG_NO_FREE, CSV_EXPECT_LOG_NO_UNIQUE, CSV_EXPECT_DATE, CSV_EXPECT_DURATION,
    CSV_EXPECT_DURATION_RANGE, CSV_EXPECT_REGISTRATION, CSV_EXPECT_AIRFIELD, CSV_EXPECT_ROLE, CSV_EXPECT_LAUNCH_TYPE,
    CSV_EXPECT_PIC, CSV_EXPECT_TIME, CSV_EXPECT_AFTER_LAUNCH, CSV_EXPECT_ONE_LANDING, CSV_EXPECT_FLIGHT_ROW,
    CSV_EXPECT_GLIDER_TYPE, CSV_EXPECT_LATITUDE, CSV_EXPECT_LONGITUDE, CSV_EXPECT_BOTH_COORDINATES, CSV_EXPECT_YES_NO, CSV_UNUSED_COLUMN,
    CSV_SKIP_GLIDER_EXISTS, CSV_SKIP_AIRFIELD_EXISTS, CSV_SKIP_REPEAT,

    // Backup file, restore and merge
    BACKUP_NOT_JSON, BACKUP_NOT_BACKUP, BACKUP_NO_VERSION, BACKUP_NEWER, BACKUP_UNKNOWN_VERSION, BACKUP_NO_UPGRADE,
    BACKUP_DAMAGED, BACKUP_NEEDS_EMPTY, BACKUP_FILE_UNREADABLE, BACKUP_FOLDER_REFUSED, BACKUP_WRITE_FAILED, BACKUP_FAILED,

    // Backup validation: what a problem is about, then the problems
    BK_TABLE_LAUNCH_TYPES, BK_TABLE_CLUBS, BK_TABLE_AIRFIELDS, BK_TABLE_GLIDERS, BK_TABLE_FLIGHTS, BK_TABLE_IMPORT_BATCHES,
    BK_LAUNCH_TYPE, BK_CLUB, BK_AIRFIELD, BK_GLIDER, BK_FLIGHT, BK_BALANCE, BK_BATCH,
    BK_DUPLICATE_ID, BK_NO_TIME, BK_BAD_TIME, BK_NO_NAME, BK_NO_REGISTRATION, BK_MISSING_CLUB, BK_DEFAULT_CLUB,
    BK_MISSING_LAUNCH_TYPE, BK_ONE_COORDINATE, BK_LATITUDE_RANGE, BK_LONGITUDE_RANGE, BK_BAD_LOGBOOK_DATE,
    BK_LOG_NO_POSITIVE, BK_BAD_DATE, BK_DURATION_RANGE, BK_MISSING_GLIDER, BK_MISSING_AIRFIELD,
    BK_MISSING_LANDING_AIRFIELD, BK_BOTH_LANDING, BK_UNKNOWN_ROLE, BK_UNKNOWN_SOURCE, BK_NO_PIC, BK_BAD_LAUNCH_TIME,
    BK_BAD_LANDING_TIME, BK_LANDING_BEFORE_LAUNCH, BK_BALANCE_ROLE, BK_BALANCE_NEGATIVE, BK_BALANCE_DATE,
    BK_BALANCE_DUPLICATE, BK_LOG_NO_COLLISION, BK_DUPLICATE_KEY,
    BK_TABLE_WITNESS_SIGNOFFS, BK_WITNESS, BK_WITNESS_NO_CONSENT, BK_WITNESS_DANGLING,
    BK_PHOTO_NOT_BASE64, BK_PHOTO_NOT_JPEG, BK_PHOTO_TOO_LARGE, BK_PHOTO_HASH,

    // WeGlide
    WEGLIDE_STATUS, WEGLIDE_NO_HOST, WEGLIDE_UNREACHABLE, WEGLIDE_NO_LIST, AIRCRAFT_SAVE_FAILED,

    // IGC import
    IGC_NO_DATE, IGC_NO_FIXES, IGC_NO_FLIGHT, IGC_UNREADABLE,

    // LXNAV logger download
    LXNAV_CONNECT_FAILED, LXNAV_NO_LOGBOOK, LXNAV_GAVE_UP, LXNAV_SIZE_MISMATCH,

    // Logbook PDF
    PDF_TEMPLATE_UNREADABLE, PDF_TEMPLATE_NEWER, PDF_TEMPLATE_PROBLEM,

    // Witness sign-off
    WITNESS_NAME_REQUIRED, WITNESS_NO_FLIGHTS, WITNESS_IS_PILOT, WITNESS_NOT_PIC, WITNESS_PHOTO_REQUIRED,
}
